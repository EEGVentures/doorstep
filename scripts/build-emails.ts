// Embeds emails/*.html into server/email/templates.generated.ts so Vercel functions
// never depend on reading files at runtime. Run after editing a template: npm run email:build
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, basename } from 'node:path';

const dir = join(import.meta.dirname, '..', 'emails');
const files = readdirSync(dir).filter((f) => f.endsWith('.html')).sort();
const entries = files.map((f) => `  ${JSON.stringify(basename(f, '.html'))}: ${JSON.stringify(readFileSync(join(dir, f), 'utf8'))},`);
writeFileSync(
  join(import.meta.dirname, '..', 'server', 'email', 'templates.generated.ts'),
  `// Generated by scripts/build-emails.ts from emails/*.html. Do not edit by hand.\nexport const TEMPLATES = {\n${entries.join('\n')}\n} as const;\nexport type TemplateId = keyof typeof TEMPLATES;\n`,
);
console.log(`embedded ${files.length} templates`);
